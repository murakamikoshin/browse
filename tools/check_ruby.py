"""ふりがなの読みを機械で見る。

日本語の数え方は、数と助数詞の組で音が変わる（一本＝いっぽん、三本＝さんぼん）。
辞書は表記から読みを引いているだけなので、ここが素通りする。規則で当たりを付けて並べる。
**判断は人がする。** 直すのは scenario/ruby_fix.md。

  python3 tools/check_ruby.py
"""
import io, re, sys, json

NUM = {"一": "いち", "二": "に", "三": "さん", "四": "よん", "五": "ご", "六": "ろく",
       "七": "なな", "八": "はち", "九": "きゅう", "十": "じゅう", "百": "ひゃく",
       "千": "せん", "何": "なん"}

# 助数詞ごとの、正しい読み。数ごとに違うものだけ書く
CNT = {
    "本": {"一": "いっぽん", "三": "さんぼん", "六": "ろっぽん", "八": "はっぽん",
           "十": "じっぽん", "何": "なんぼん", "二": "にほん", "四": "よんほん",
           "五": "ごほん", "七": "ななほん", "九": "きゅうほん"},
    "人": {"一": "ひとり", "二": "ふたり", "三": "さんにん", "四": "よにん",
           "何": "なんにん"},
    "分": {"一": "いっぷん", "三": "さんぷん", "四": "よんぷん", "六": "ろっぷん",
           "八": "はっぷん", "十": "じっぷん", "何": "なんぷん"},
    "匹": {"一": "いっぴき", "三": "さんびき", "六": "ろっぴき", "十": "じっぴき"},
    "杯": {"一": "いっぱい", "三": "さんばい", "六": "ろっぱい", "十": "じっぱい"},
    "冊": {"一": "いっさつ", "八": "はっさつ", "十": "じっさつ"},
    "通": {"一": "いっつう", "八": "はっつう", "十": "じっつう"},
    "件": {"一": "いっけん", "六": "ろっけん", "八": "はっけん", "十": "じっけん"},
    "軒": {"一": "いっけん", "三": "さんげん", "六": "ろっけん", "十": "じっけん"},
    "歩": {"一": "いっぽ", "三": "さんぽ", "六": "ろっぽ", "十": "じっぽ"},
    "艘": {"一": "いっそう", "八": "はっそう", "十": "じっそう"},
    "足": {"一": "いっそく", "三": "さんぞく", "八": "はっそく", "十": "じっそく"},
    "階": {"一": "いっかい", "三": "さんがい", "六": "ろっかい", "十": "じっかい"},
    "枚": {}, "台": {}, "円": {}, "年": {}, "度": {}, "秒": {}, "時": {}, "回": {},
}


def dic(html):
    return json.loads(re.search(r"\nvar RUBY=(\{.*?\});\n", html, re.S).group(1))


if __name__ == "__main__":
    R = dic(io.open("game.html", encoding="utf-8").read())
    bad = []
    for k, v in sorted(R.items()):
        m = re.match(r"^([一二三四五六七八九十百千何])(.)", k)
        if not m:
            continue
        n, c = m.group(1), m.group(2)
        if c not in CNT:
            continue
        want = CNT[c].get(n)
        if not want:
            continue
        head = v.split("|")[0]
        if not head.startswith(want[:len(want)]) and head != want:
            bad.append((k, v, want))
    print("数え方の当たり %d件" % len(bad))
    for k, v, want in bad:
        print("   %-12s いま %-22s → %s ではないか" % (k, v, want))
    if not bad:
        print("   気になるものはありません")

    # 一文字の語で、人の名前としても読める字
    NAMEY = {"章": "しょう", "甲": "こう", "万": "まん", "角": "かど",
             "米": "こめ", "凪": "なぎ", "汐": "しお"}
    n2 = [(k, R[k]) for k in NAMEY if k in R and NAMEY[k] and R[k] != NAMEY[k]]
    print("\n名前の読みが混じっていそうな字 %d件" % len(n2))
    for k, v in n2:
        print("   %s  いま %s" % (k, v))
    if not n2:
        print("   気になるものはありません")
